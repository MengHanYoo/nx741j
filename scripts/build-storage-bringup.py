#!/usr/bin/env python3
"""Build and fold the storage ABI support into build/sheng-ufs/libShengUfs.a.

The archive ends up containing:
  * IOBlockStorageDevice-reference.o  (official ABI audit reference object)
  * verified_root.o / xnu_crypto.o    (real VerifiedRoot implementation)
  * Stubs.o                           (owner-key/policy anchors + board diagnostic hook)
  * Policy.o                          (only when build/verified-root holds an envelope:
                                       real owner key + signed manifest, replaces the anchors)
  * SmmuBind.o + ArmSmmu4K.o          (the board binding that calls the ArmSmmu4K kit,
                                       and the kit itself, which has no archive of its own)

No kernel build-script patch is required: ShengUfs is already force-loaded by the
native-UFS branch, so appending the members to its archive makes them part of the link.

The policy inputs come from scripts/mk-verified-root-policy.py:

    scripts/mk-verified-root-policy.py --kit <tree>/kits/VerifiedRoot \\
        --image <image> --volume-uuid <uuid> --generation 1 \\
        --output build/verified-root --private-key <outside the tree>

Only the envelope has to be in place before the kernel build; the image itself is
not read here. A large envelope (over --max-policy-bytes) is refused because it has
to be delivered at run time instead of being compiled into the kernel.
"""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/storage-bringup'


def anchor_source():
    """Stubs.c from the device kit when it is mapped, else the merged package copy."""
    for candidate in sorted((ROOT / 'kits').glob('*/storage-bringup/Stubs.c')):
        if candidate.is_file():
            return candidate
    fallback = ROOT / 'package/storage-bringup/Stubs.c'
    if fallback.is_file():
        return fallback
    raise SystemExit('Stubs.c not found under kits/ or package/')
OUT.mkdir(parents=True, exist_ok=True)

parser = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument('--policy', type=Path, default=ROOT / 'build/verified-root',
                    help='directory with trusted-key.bin and manifest.bin (default: build/verified-root)')
parser.add_argument('--max-policy-bytes', type=int, default=1024 * 1024,
                    help='refuse to embed an envelope larger than this (default: 1 MiB)')
args = parser.parse_args()

reference = ROOT / 'build/storage-abi/IOBlockStorageDevice-reference.o'
if not reference.is_file():
    raise SystemExit('Missing build/storage-abi/IOBlockStorageDevice-reference.o; run scripts/audit-storage-interface.py')

record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/osfmk/DEVELOPMENT/startup.o.json').read_text().strip().rstrip(','))

def compile_c(source: Path, obj: Path, extra=()):
    command, args, i = [], record['arguments'], 0
    while i < len(args):
        a = args[i]
        if a == record['file']:
            command.append(str(source))
        elif a in ('-o', '-MF', '-MT', '-MJ'):
            if a == '-o':
                command += ['-o', str(obj)]
            i += 1
        elif a == '-Xclang' and args[i + 1].startswith('-W'):
            i += 1
        elif not a.startswith(('-W', '-DXNU_BOOT_PROGRESS=')):
            command.append(a)
        i += 1
    command += ['-mgeneral-regs-only', '-Wall', '-Wextra', '-Werror',
                '-I', str(ROOT / '.cache/xnu-work/osfmk'),
                '-I', str(ROOT / 'kits/VerifiedRoot/include')]
    command += list(extra)
    subprocess.run(command, cwd=record['directory'], check=True, timeout=120)


def policy_source(policy: Path):
    key = policy / 'trusted-key.bin'
    envelope = policy / 'manifest.bin'
    if not key.is_file() or not envelope.is_file():
        return None
    key_bytes = key.read_bytes()
    envelope_bytes = envelope.read_bytes()
    if len(key_bytes) != 395:
        raise SystemExit(f'{key} must be 395 bytes, got {len(key_bytes)}')
    if not envelope_bytes:
        raise SystemExit(f'{envelope} is empty')
    if len(envelope_bytes) > args.max_policy_bytes:
        raise SystemExit(
            f'{envelope} is {len(envelope_bytes)} bytes, over the {args.max_policy_bytes}-byte '
            'embed limit; deliver the envelope at run time instead of compiling it in')
    if not envelope_bytes.startswith(b'VROOT01\x00'):
        raise SystemExit(f'{envelope} does not hold a VROOT01 header')

    def array(name, decl, data, qualifier='static '):
        lines = [f'{qualifier}{decl} = {{']
        for start in range(0, len(data), 16):
            chunk = ', '.join(f'0x{byte:02x}' for byte in data[start:start + 16])
            lines.append(f'    {chunk},')
        lines.append('};')
        return '\n'.join(lines)

    return '\n'.join([
        '/* generated by scripts/build-storage-bringup.py -- do not edit */',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        array('verified_root_key', 'uint8_t verified_root_key[395]', key_bytes, qualifier=''),
        '',
        array('envelope', 'uint8_t verified_root_policy_0[%d]' % len(envelope_bytes), envelope_bytes),
        '',
        'void *verified_root_policies[16] = { (void *)verified_root_policy_0 };',
        'uint64_t verified_root_policy_count = 1;',
        '',
    ])


def main():
    stubs = anchor_source()
    # ArmSmmu4K is a kit: no archive of its own, so the consumer compiles the
    # translation code in and carries it in its archive. Decided before Stubs.c
    # because the kit also owns the boot_progress_poll hook.
    smmu_kit = ROOT / 'kits/ArmSmmu4K'
    smmu, bound = [], []
    if smmu_kit.is_dir():
        bound = ['-DVR_SMMU_BOUND']
    policy = policy_source(args.policy)
    if policy is not None:
        (OUT / 'Policy.c').write_text(policy)
        compile_c(OUT / 'Policy.c', OUT / 'Policy.o', ['-DVR_POLICY_BUILT_IN'])
        compile_c(stubs, OUT / 'Stubs.o', ['-DVR_POLICY_BUILT_IN', *bound])
        members = [OUT / 'Policy.o']
        print(f'== storage-bringup: policy {args.policy} compiled in')
    else:
        compile_c(stubs, OUT / 'Stubs.o', bound)
        members = []
        print(f'== storage-bringup: no envelope in {args.policy}, policy table stays empty (fail closed)')

    compile_c(ROOT / 'kits/VerifiedRoot/src/verified_root.c', OUT / 'verified_root.o')
    compile_c(ROOT / 'kits/VerifiedRoot/adapters/xnu_crypto.c', OUT / 'xnu_crypto.o')

    if smmu_kit.is_dir():
        # the kit is a set of translation units, not one file: compile all of them
        for source in sorted(smmu_kit.glob('*.c')):
            if source.stem.lower().startswith(('test', 'audit_test')):
                continue
            compile_c(source, OUT / (source.stem + '.o'), ['-I', str(smmu_kit)])
            smmu.append(OUT / (source.stem + '.o'))
        compile_c(stubs.parent / 'SmmuBind.c', OUT / 'SmmuBind.o', ['-I', str(smmu_kit)])
        smmu.append(OUT / 'SmmuBind.o')
        print(f'== storage-bringup: ArmSmmu4K bound from {smmu_kit} ({len(smmu)} objects)')
    else:
        print(f'== storage-bringup: {smmu_kit} missing, SMMU binding skipped')

    archive = ROOT / 'build/sheng-ufs/libShengUfs.a'
    if not archive.is_file():
        raise SystemExit('Missing build/sheng-ufs/libShengUfs.a; build the ShengUfs component first')
    # llvm-ar r only adds or replaces: drop the members this recipe owns first, so a
    # build without a policy cannot keep a stale Policy.o that defines the same
    # symbols as Stubs.o.
    for name in ('IOBlockStorageDevice-reference.o', 'verified_root.o', 'xnu_crypto.o', 'Stubs.o', 'Policy.o',
                 *[member.name for member in smmu]):
        subprocess.run(['llvm-ar', 'd', str(archive), name],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
    subprocess.run(['llvm-ar', 'r', str(archive), str(reference),
                    str(OUT / 'verified_root.o'), str(OUT / 'xnu_crypto.o'), str(OUT / 'Stubs.o'),
                    *map(str, members), *map(str, smmu)], check=True, timeout=120)
    print(f'== storage-bringup: folded into {archive}')


if __name__ == '__main__':
    main()
