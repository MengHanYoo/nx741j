#!/usr/bin/env python3
"""Derive the ADT source from the device's own device tree.

The board file dts/nx741j.dts describes only what the hand-written fragments
model.  The device's real tree (911 KB, ~5.3 k nodes, dumped from the running
firmware) carries every node and, more usefully, the properties the ADT
generator exports: clocks, iommus, dma-coherent, real GIC ranges.

    scripts/mk-adt-dts.py --dtb stock/dt/live_fdt.dtb --out dts/nx741j-adt.dts

Four normalisations are needed before unixnu.devicetree.generate accepts it:
  1. /memory lists DRAM as many carve-out ranges; the handoff needs the one
     contiguous range the loader owns (0x8C0000000 + 5 GiB, from board.toml).
  2. /psci lives under /soc; the generator looks for it at the root.
  3. /cpus carries no timebase-frequency.
  4. /cpus also holds cpu-map and idle-states, which the generator would read
     as CPUs.
Plus: the vendor root identity is a Qualcomm MTP reference, so the board's own
model/compatible are applied on top, and the nodes to export get unixnu,adt-name.
"""
import argparse
import pathlib
import subprocess
import sys

FRAGMENT = """
/* --- generated by scripts/mk-adt-dts.py: ADT normalisation --- */
/ {
    model = "Nubia Z80 Ultra (NX741J)";
    compatible = "nubia,nx741j", "qcom,alor", "qcom,sm8850";
    memory {
        device_type = "memory";
        reg = <0x8 0xc0000000 0x1 0x40000000>;
    };
    psci {
        compatible = "arm,psci-1.0";
        method = "smc";
    };
    cpus {
        timebase-frequency = <19200000>;
        /delete-node/ cpu-map;
        /delete-node/ idle-states;
    };
};

&{/soc/interrupt-controller@17000000} { unixnu,adt-name = "intc"; };
&{/soc/timer} { unixnu,adt-name = "arm-timer"; };
&{/soc/ufshc@1d84000} { unixnu,adt-name = "ufshc"; };
"""


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dtb', default='stock/dt/live_fdt.dtb')
    parser.add_argument('--out', default='dts/nx741j-adt.dts')
    args = parser.parse_args(argv[1:])

    dtb = pathlib.Path(args.dtb)
    if not dtb.is_file():
        raise SystemExit(f'{dtb}: not found (dump the live tree first)')
    text = subprocess.check_output(['dtc', '-I', 'dtb', '-O', 'dts', str(dtb)], text=True,
                                   stderr=subprocess.DEVNULL)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + FRAGMENT)
    nodes = text.count('{')
    print(f'{out}: {nodes} source nodes from {dtb} ({dtb.stat().st_size} B)')


if __name__ == '__main__':
    main(sys.argv)
